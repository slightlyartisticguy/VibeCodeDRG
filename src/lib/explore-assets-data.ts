/**
 * Curated asset groups for the Explore Assets section.
 * Each group has a default symbol list and optional year-specific overrides.
 * Symbols include short display names to avoid extra API calls.
 */

export type AssetGroupCategory =
  | "sector"
  | "theme"
  | "asset-class"
  | "event"
  | "market";

export type SectorFilter =
  | "All"
  | "Technology"
  | "Healthcare"
  | "Energy"
  | "Financials"
  | "Consumer"
  | "Industrials"
  | "Materials"
  | "Utilities"
  | "Real Estate"
  | "Communications"
  | "Precious Metals"
  | "Crypto"
  | "Biotech";

export type MarketFilter = "All" | "US" | "International" | "Crypto";

export interface SymbolEntry {
  symbol: string;
  name: string;
}

export interface AssetGroup {
  id: string;
  /** Title shown in the card. Use [year] placeholder. */
  title: string;
  /** Short description. Use [year] placeholder. */
  description: string;
  category: AssetGroupCategory;
  sector: SectorFilter;
  market: MarketFilter;
  /** Default symbol list, used when no year-specific override exists. */
  defaultSymbols: SymbolEntry[];
  /** Year-specific symbol overrides keyed by 4-digit year. */
  yearSymbols?: Record<number, SymbolEntry[]>;
  /** Metric used to sort assets within the card. */
  sortBy: "yearReturn" | "volume";
  /** Controls bento grid width. */
  layout: "wide" | "normal";
  /** Icon name (lucide) */
  icon: string;
}

