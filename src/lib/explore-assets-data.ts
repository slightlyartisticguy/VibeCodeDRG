/**
 * Returns the symbols to use for a given group in a given year.
 */
export function getGroupSymbols(group: AssetGroup, year: number): SymbolEntry[] {
  return group.yearSymbols?.[year] ?? group.defaultSymbols;
}

/**
 * Filter groups by sector and market.
 */
export function filterGroups(
  groups: AssetGroup[],
  sector: SectorFilter,
  market: MarketFilter
): AssetGroup[] {
  return groups.filter((g) => {
    const sectorMatch = sector === "All" || g.sector === sector || g.sector === "All";
    const marketMatch = market === "All" || g.market === market;
    return sectorMatch && marketMatch;
  });
}
